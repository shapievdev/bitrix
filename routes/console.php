<?php

use Illuminate\Support\Facades\Schedule;

/*
|--------------------------------------------------------------------------
| Расписание
|--------------------------------------------------------------------------
|
| События портала теряются — доставка не гарантирована, а если приложение
| было недоступно, Битрикс перестаёт их слать совсем. Регулярный полный
| обход возвращает доски в согласованное состояние.
|
*/

Schedule::command('bitrix:sync-boards')
    ->everyThirtyMinutes()
    ->withoutOverlapping()
    ->runInBackground();
